# 練習02【LED・for】
# for文を使い、LEDを3回点滅させてください。
# 1回の点滅は、0.5秒点灯・0.5秒消灯とします。
#
# 【作業の指示】
# このコメントの下に、自分でコードを書いてください。
# 必要な道具は、同じフォルダのlesson_toolsから読み込んで使います。
# 関数定義・with・クラスは使わず、習った命令と構文で書いてください。
# 字下げには半角スペース4個を使います。
# led_on：LEDを点ける。led_off：LEDを消す。sleep：指定した秒数だけ待つ。
# LEDはGPIO12に接続し、抵抗330 Ωを必ず入れてください。
# プログラムの最後にはLEDを消してください。
# dry_runでGPIOに触れずに確認してから、実機で試してください。
# 実機確認の前に模擬実行の指定を外し、Thonnyでは実行環境を再起動します。
